"""Instantiate data files as Python variables."""
from pathlib import Path
import pprint
import yaml

def find_git_root(path: Path) -> Path:
    """Find the root directory of the git repository containing the given path."""
    path = path.resolve()
    if path.is_file():
        path = path.parent
    for directory in [path, *path.parents]:
        if (directory / ".git").is_dir():
            return directory
    raise FileNotFoundError(f"Could not find .git directory from {path}")


def path_relative_to_git_dir(path: Path) -> Path:
    """Return the given path relative to the git root directory."""
    return path.resolve().relative_to(find_git_root(path))


def midi_constants():
    """Generate midi_tools/constants.py with MIDI program names mapped from YAML data."""
    with open('data/midi-programs.yaml', 'r') as fileh:
        loaded_data = yaml.safe_load(fileh)

    mapping = {
        int(key) - 1: value
        for key, value in loaded_data.items()
    }

    with open('midi_tools/constants.py', 'w') as out:
        out.write(f'''# Generated by {path_relative_to_git_dir(Path(__file__))}.\n''')
        out.write('MIDI_PROGRAMS = ')
        pprint.pp(mapping, stream=out)

def main():
    midi_constants()

if __name__ == "__main__":
    main()
